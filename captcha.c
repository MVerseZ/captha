/* ---------- symbols ---------- */
static int char_index(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'A' && c <= 'Z') return 10 + (c - 'A');
    if (c >= 'a' && c <= 'z') return 10 + (c - 'a');
    return -1;
}

/* ---------- rotate ---------- */
static void draw_char_rotated(unsigned char *img, char c, int cx, int cy,
                              int scale, double angle,
                              const unsigned char *font, int font_h,
                              unsigned char r, unsigned char g, unsigned char b,
                              double alpha) {
    int idx = char_index(c);
    if (idx < 0) return;

    int src_w = 5, src_h = font_h;
    int out_w = (int)(src_w * scale * 2.0);
    int out_h = (int)(src_h * scale * 2.0);

    double cos_a = cos(angle);
    double sin_a = sin(angle);

    for (int oy = -out_h / 2; oy < out_h / 2; oy++) {
        for (int ox = -out_w / 2; ox < out_w / 2; ox++) {
            int sx = (int)( ox * cos_a + oy * sin_a);
            int sy = (int)(-ox * sin_a + oy * cos_a);

            int col = (sx + (src_w * scale) / 2) / scale;
            int row = (sy + (src_h * scale) / 2) / scale;

            if (col < 0 || col >= src_w || row < 0 || row >= src_h) continue;

            int bit = (font[idx * src_h + row] >> (4 - col)) & 1;
            if (bit) {
                if (alpha >= 1.0)
                    set_pixel(img, cx + ox, cy + oy, r, g, b);
                else
                    blend_pixel(img, cx + ox, cy + oy, r, g, b, alpha);
            }
        }
    }
}

/* ---------- blur box  ---------- */
static void blur(unsigned char *img, int radius) {
    unsigned char *tmp = malloc(WIDTH * HEIGHT * CHANNELS);
    if (!tmp) return;
    memcpy(tmp, img, WIDTH * HEIGHT * CHANNELS);

    for (int y = 0; y < HEIGHT; y++) {
        for (int x = 0; x < WIDTH; x++) {
            int sum_r = 0, sum_g = 0, sum_b = 0, count = 0;
            for (int dy = -radius; dy <= radius; dy++) {
                for (int dx = -radius; dx <= radius; dx++) {
                    int nx = x + dx, ny = y + dy;
                    if (nx < 0 || nx >= WIDTH || ny < 0 || ny >= HEIGHT) continue;
                    int idx = (ny * WIDTH + nx) * CHANNELS;
                    sum_r += tmp[idx + 0];
                    sum_g += tmp[idx + 1];
                    sum_b += tmp[idx + 2];
                    count++;
                }
            }
            int idx = (y * WIDTH + x) * CHANNELS;
            img[idx + 0] = (unsigned char)(sum_r / count);
            img[idx + 1] = (unsigned char)(sum_g / count);
            img[idx + 2] = (unsigned char)(sum_b / count);
        }
    }
    free(tmp);
}

