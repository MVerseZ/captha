/* ---------- randomizing ---------- */
static unsigned int seed_state;
static unsigned int xorshift(void) {
    seed_state ^= seed_state << 13;
    seed_state ^= seed_state >> 17;
    seed_state ^= seed_state << 5;
    return seed_state;
}
static int rand_range(int min, int max) {
    return min + (int)(xorshift() % (max - min + 1));
}
static double rand_double(void) {
    return (double)xorshift() / 4294967295.0;
}

/* ---------- basew ---------- */
static void set_pixel(unsigned char *img, int x, int y,
                      unsigned char r, unsigned char g, unsigned char b) {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    int idx = (y * WIDTH + x) * CHANNELS;
    img[idx + 0] = r;
    img[idx + 1] = g;
    img[idx + 2] = b;
}

static void blend_pixel(unsigned char *img, int x, int y,
                        unsigned char r, unsigned char g, unsigned char b,
                        double alpha) {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    int idx = (y * WIDTH + x) * CHANNELS;
    img[idx + 0] = (unsigned char)(img[idx + 0] * (1 - alpha) + r * alpha);
    img[idx + 1] = (unsigned char)(img[idx + 1] * (1 - alpha) + g * alpha);
    img[idx + 2] = (unsigned char)(img[idx + 2] * (1 - alpha) + b * alpha);
}

static void draw_line(unsigned char *img, int x0, int y0, int x1, int y1,
                      unsigned char r, unsigned char g, unsigned char b) {
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    while (1) {
        set_pixel(img, x0, y0, r, g, b);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

